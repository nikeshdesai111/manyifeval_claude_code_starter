def tab_cv_summary():
    rows_cfg = ["REF_constant", "REF_type", "REF_type_k", "REF_structure", None, "B1", "B2", None,
                "H1", "H2", "A1", "H1+A1", "H2+A1", "H1+H2+A1", None]
    cells = {k: cell(*k) for k in CELL}
    best = {k: v[v.family != "reference"].cv_loss.min() for k, v in cells.items()}
    rows = []
    for c in rows_cfg:
        if c is None:
            rows.append(None); continue
        r = [nm(c)]
        for k in CELL:
            v = cells[k].cv_loss[c]
            s = loss(v, k[1])
            r.append(f"\\textbf{{{s}}}" if abs(v - best[k]) < 1e-12 else s)
        rows.append(r)
    for fam, lab in (("B1 family", "Best B1 + probe"), ("B2 family", "Best B2 + probe")):
        r = [lab]
        for k in CELL:
            d = cells[k]; d = d[(d.family == fam) & (d.index != fam[:2])]
            c = d.cv_loss.idxmin(); s = loss(d.cv_loss[c], k[1])
            s = f"\\textbf{{{s}}}" if abs(d.cv_loss[c] - best[k]) < 1e-12 else s
            r.append(f"{s} {{\\scriptsize({c})}}")
        rows.append(r)
    rows.append(None)
    r = ["Of 23 below structure head"]
    for k in CELL:
        d = cells[k]
        r.append(str(int((d[d.family != "reference"].cv_loss < d.cv_loss["REF_structure"]).sum())))
    rows.append(r)
    head = [r" & \multicolumn{2}{c}{Llama 3.1 8B} & \multicolumn{2}{c}{Qwen3-8B} \\", r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
            r"Predictor & Obj.~1 NLL & Obj.~2 MSE & Obj.~1 NLL & Obj.~2 MSE \\"]
    # reorder columns to (llama1, llama2, qwen1, qwen2) = CELL order already
    write("tab_cv_summary", tabular("lcccc", head, rows))


def tab_oof():
    def piv(m, o):
        d = M[(M.model == m) & (M.objective == o)]
        return d.pivot(index="config", columns="metric", values="est"), d.pivot(index="config", columns="metric", values="lo"), \
            d.pivot(index="config", columns="metric", values="hi")
    base = ["REF_type_k", "REF_structure", "B1", "B2", "H1", "H2", "A1"]
    for o, mets, heads in ((1, [("nll", 4), ("brier", 4), ("auroc", 3), ("risk_top", 3), ("risk_bottom", 3)],
                            ["NLL", "Brier", "AUROC", "Top 10\\%", "Bottom 10\\%"]),
                           (2, [("rmse", 4), ("mae", 4), ("pearson", 3), ("spearman", 3)],
                            ["RMSE", "MAE", "Pearson", "Spearman"])):
        rows = []
        for m in ("llama", "qwen"):
            est, lo, hi = piv(m, o)
            d = cell(m, o)
            po = d[d.family == "probe-only"].cv_loss.idxmin()
            al = d[d.family != "reference"].cv_loss.idxmin()
            order = list(dict.fromkeys(base + [po, al]))
            if rows:
                rows.append(None)
            for i, c in enumerate(order):
                tag = "" if c in base else (" (best probe-only)" if c == po and c != al else
                                            " (lowest CV loss)" if c == al and c != po else " (best probe-only; lowest CV loss)")
                if c in base and c == al:
                    tag = " (lowest CV loss)"
                r = [GEN[m] if i == 0 else "", nm(c) + (f"\\,{{\\scriptsize{tag.strip()}}}" if tag else "")]
                for k, dd in mets:
                    r.append(f(est.loc[c, k], dd))
                r.insert(3, f"{{\\scriptsize[{f(lo.loc[c, mets[0][0]], 4)}, {f(hi.loc[c, mets[0][0]], 4)}]}}")
                rows.append(r)
        head = [" & ".join(["", "Predictor", heads[0], "95\\% interval"] + heads[1:]) + r" \\"]
        write(f"tab_oof_obj{o}", tabular("ll" + "c" * (len(mets) + 1), head, rows))


def tab_best_vs():
    d = C[C.family == "Best probe-only vs comparator"]
    rows, last = [], None
    for r in d.itertuples():
        key = (r.model, r.objective)
        if last is not None and key != last:
            rows.append(None)
        first = key != last; last = key
        dd = 4
        rows.append([f"{GEN[r.model]}, Obj.~{r.objective}" if first else "", r.b if first else "", nm(r.a),
                     f"${100 * (r.cv_loss_b - r.cv_loss_a) / r.cv_loss_a:+.1f}\\%$",
                     ci(r.diff, r.lo, r.hi, dd, sign=True), f"{r.folds_b_lower}/5"])
    head = [r"Cell & Best probe-only & Comparator & $\Delta$ CV loss & $\Delta$ primary metric, OOF [95\% interval] & Folds \\"]
    write("tab_best_vs", tabular("lllccc", head, rows))


def tab_full_cv():
    for m in ("llama", "qwen"):
        a, b = cell(m, 1), cell(m, 2)
        rows, fam = [], None
        for c in a.index:
            if fam is not None and a.family[c] != fam:
                rows.append(None)
            fam = a.family[c]
            r = [nm(c)]
            for d, o in ((a, 1), (b, 2)):
                x = d.loc[c]
                st = x.setting.replace("fitting-fold rates", "rates").replace("_l2=", ", ").replace("linear", "lin").replace("mlp", "MLP")
                ep = "" if pd.isna(x.epoch) else f"/{int(x.epoch)}"
                nf = "--" if pd.isna(x.n_features) else f"{int(x.n_features):,}"
                r += [nf, st + ep, loss(x.cv_loss, o), loss(x.fold_sd, o)]
            rows.append(r)
        head = [r" & \multicolumn{4}{c}{Objective 1 (NLL)} & \multicolumn{4}{c}{Objective 2 (MSE $\times 10^{-2}$)} \\",
                r"\cmidrule(lr){2-5}\cmidrule(lr){6-9}",
                r"Configuration & Width & Head, $\lambda$/epoch & CV loss & Fold SD & Width & Head, $\lambda$/epoch & CV loss & Fold SD \\"]
        write(f"tab_full_cv_{m}", tabular("lrlccrlcc", head, rows))


def tab_contrasts():
    for o in (1, 2):
        d = C[(C.objective == o) & (C.family != "Best probe-only vs comparator")]
        L, Q = d[d.model == "llama"].reset_index(drop=True), d[d.model == "qwen"].reset_index(drop=True)
        rows, fam = [], None
        for i in range(len(L)):
            l, q = L.loc[i], Q.loc[i]
            assert (l.a, l.b) == (q.a, q.b)
            if fam is not None and l.family != fam:
                rows.append(None)
            first = l.family != fam; fam = l.family
            a = l.a.replace("BETTER(", "better(").replace("REF_structure", "Structure")
            rows.append([l.family.split(" ")[0] if first and l.family.startswith("C") else ("Ref." if first else ""),
                         a, l.b, ci(l["diff"], l.lo, l.hi, 4, True), f"{l.folds_b_lower}/5",
                         ci(q["diff"], q.lo, q.hi, 4, True), f"{q.folds_b_lower}/5"])
        met = "NLL" if o == 1 else "RMSE"
        head = [r" & & & \multicolumn{2}{c}{Llama 3.1 8B} & \multicolumn{2}{c}{Qwen3-8B} \\", r"\cmidrule(lr){4-5}\cmidrule(lr){6-7}",
                rf"Family & $a$ & $b$ & $\Delta$ {met} [95\% interval] & Folds & $\Delta$ {met} [95\% interval] & Folds \\"]
        write(f"tab_contrasts_obj{o}", tabular("lllcccc", head, rows))


