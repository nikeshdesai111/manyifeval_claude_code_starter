def nm(c: str) -> str:
    return NAME.get(c, c)


def f(x, d=4):
    return "--" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f"{x:.{d}f}"


def loss(x, o):
    """Objective 1 NLL as is; Objective 2 MSE in units of 1e-2."""
    return f(x, 4) if o == 1 else f(100 * x, 3)


def ci(est, lo, hi, d=4, sign=False):
    s = "+" if sign else ""
    return f"${est:{s}.{d}f}$ {{\\scriptsize[${lo:{s}.{d}f}$, ${hi:{s}.{d}f}$]}}"


def write(name: str, body: str) -> None:
    G.mkdir(parents=True, exist_ok=True)
    (G / f"{name}.tex").write_text("% generated by report/make_tables.py -- do not edit\n" + body + "\n")


def tabular(spec: str, header: list[str], rows: list[list[str] | None]) -> str:
    out = [f"\\begin{{tabular}}{{{spec}}}", "\\toprule"] + header + ["\\midrule"]
    for r in rows:
        out.append("\\midrule" if r is None else " & ".join(r) + r" \\")
    return "\n".join(out + ["\\bottomrule", "\\end{tabular}"])


