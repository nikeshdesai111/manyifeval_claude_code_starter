def tab_per_type():
    cols = ["REF_structure", "B2", "H1", "H2", "A1"]
    for m in ("llama", "qwen"):
        d = PT[PT.model == m]
        order = d[d.config == "A1"].sort_values("violation_rate", ascending=False).type_id.tolist()
        rows = []
        for t in order:
            x = d[d.type_id == t].set_index("config")
            v = x.nll[cols]
            r = [TYPE[t][0], f(x.violation_rate["A1"], 3)]
