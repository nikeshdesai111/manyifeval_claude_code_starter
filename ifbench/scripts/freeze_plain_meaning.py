"""Freeze the plain-meaning checks: write docs/plain_meaning_checks.md and the sha256 record.

Run once at the end of stage 1. Re-running after an edit is a change to frozen definitions and
needs Nicky's approval (the test suite refuses a mismatch).
Usage: python scripts/freeze_plain_meaning.py
"""
import datetime
import hashlib
import json
import sys
from pathlib import Path

IFB = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(IFB / "src"))
from mife_ifb import inventory, plain_meaning as pm, source  # noqa: E402

MODULE = IFB / "src" / "mife_ifb" / "plain_meaning.py"
DOC = IFB / "docs" / "plain_meaning_checks.md"
RECORD = IFB / "freeze" / "plain_meaning_frozen.json"


def _cell(s):
    return s.replace("|", "\\|").replace("\n", "\\n")


def render_doc() -> str:
    out = ["# Plain-meaning checks (frozen, stage 1)", "",
           "Generated by `scripts/freeze_plain_meaning.py` from `src/mife_ifb/plain_meaning.py`; do not edit by hand.", "",
           "These checks apply to **witnesses only** (the constructed responses that prove a rule set is satisfiable). "
           "Labels for generated responses always come from the official IFBench verifiers alone.", "",
           "**G1 (every type):** the response is not blank and has at least three runs of letters.", "",
           "Each row gives the type's own condition, an example that passes the official verifier and the check, and, where "
           "the check adds something, a loophole example that the official verifier accepts but the check rejects.", "",
           "| # | Type | Check (in addition to G1 and the official verifier) | Passing example | Loophole the check rejects |",
           "|---|---|---|---|---|"]
    for i, t in enumerate(inventory.candidates(), 1):
        c = pm.CHECKS[t]
        def ex(e):
            if e is None:
                return "none needed"
            kw = {k: v for k, v in e.kwargs.items()}
            s = f"`{_cell(e.response)}`"
            if kw:
                s += f" with `{_cell(json.dumps(kw, ensure_ascii=False))}`"
            if e.task_text:
                s += " (reference text = task text)"
            if e is c.loophole:
                s += f" — rejected: {_cell(pm.check(t, e.response, e.kwargs, e.task_text)[1])}"
            return s
        out.append(f"| {i} | `{t}` | {_cell(c.rule)} | {ex(c.ok)} | {ex(c.loophole)} |")
    n_add = sum(c.loophole is not None for c in pm.CHECKS.values())
    out += ["", f"{n_add} of {len(pm.CHECKS)} types add a condition; {len(pm.CHECKS) - n_add} rely on G1 plus the official verifier.", ""]
    return "\n".join(out)


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main():
    assert set(pm.CHECKS) == set(inventory.candidates()), "one check per candidate type"
    DOC.write_text(render_doc(), encoding="utf-8")
    rec = {
        "frozen_on": datetime.date.today().isoformat(),
        "stage": 1,
        "module": str(MODULE.relative_to(IFB)), "module_sha256": sha(MODULE),
        "doc": str(DOC.relative_to(IFB)), "doc_sha256": sha(DOC),
        "ifbench_commit": source.source_commit(),
        "types": inventory.candidates(),
        "types_with_added_condition": sorted(t for t, c in pm.CHECKS.items() if c.loophole is not None),
    }
    RECORD.write_text(json.dumps(rec, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({k: rec[k] for k in ("module_sha256", "doc_sha256")}, indent=2))


if __name__ == "__main__":
    main()
