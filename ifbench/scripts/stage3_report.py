"""Write docs/stage3_report.md from freeze/stage3_summary.json and the proofs module."""
import json
import sys
from pathlib import Path

IFB = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(IFB / "src"))
from mife_ifb import stage3_proofs as P  # noqa: E402

S = json.loads((IFB / "freeze" / "stage3_summary.json").read_text())
c = lambda p: " + ".join(f"`{t}`" for t in p)  # noqa: E731
WHY = {"hand_witness": "a hand-written witness passes every check, so the pair is feasible; the builder writes one "
       "layout at a time",
       "loophole_only": "only constructions that glue words together pass", "timed_out": "50 draws did not finish within an hour",
       "fixed_seed": "both rules fixed: the single version found no witness in 24 attempts",
       "no_witness_no_proof": "no witness and no proof"}

L = ["# Stage 3 report: pairwise compatibility audit and six-rule pilot", "",
     "Generated by `scripts/stage3_report.py` from `freeze/stage3_summary.json` (built by `scripts/stage3_summary.py`). "
     "Every number below comes from that file.", "",
     "## Method", "",
     f"- All {S['pairs']} pairs of the 42 candidate types. Each *version* of a pair (one setting of its parameters) "
     f"gets exactly {S['attempts']} seeded builder attempts. Versions per pair (Nicky, 2026-11-24): **one** if both "
     "rules are fixed; **every parameter combination** if the pair has fewer than 50 (list separators, conjunction, "
     "repeat, increment, number and pronoun counts); otherwise **50 parameter draws** from the released default "
     f"generators (seed {S['seed']}). Pairs by category: {S['pairs_by_category']['fixed']} fixed, "
     f"{S['pairs_by_category']['all_combinations']} all-combinations, {S['pairs_by_category']['draws']} 50-draw.",
     "- A witness must pass both official verifiers and both frozen plain-meaning checks.",
     "- A pair is **compatible** if any version gives a witness; the success share is witnesses / versions. For a "
     "fixed pair the share is 0 or 1.",
     f"- Versions already run in the final pairwise run were replayed from their records (the builder is "
     f"deterministic); {S['new_versions']} versions were run with the current builder: the combinations the final "
     "run never drew, and every version of the 39 `format:thesis` pairs after the thesis fix (full stop inside "
     "`</i>` under `words:last_first`, approved 2026-11-24), which only that layout branch can affect "
     f"(`scripts/stage3_versions.py`). {S['versions_run']} versions in total.",
     "- Every pair without a witness was investigated: it is either a **proven conflict** (a written argument in "
     "`src/mife_ifb/stage3_proofs.py`; the library facts it relies on are tested) or **unsupported by the builder**. "
     "Both lists stay in the inventory; neither pair is co-sampled.",
     "- `ratio:overlap` is run against task texts: 222 provisional base tasks (released prompts with the rule text "
     "removed), one task per draw. Stage 4 replaces them with the cleaned task list.",
     f"- Builder: current witness.py sha256 `{S['witness_py_sha256'][:16]}…` for the thesis pairs; every other pair "
     "is replayed from the final run's builder, which differs only in the thesis branch (hashes per pair are checked "
     f"by `stage3_summary.py`: {S['builder_sha_by_pairs']}). "
     "Earlier passes (`full`, `rerun`) were used to find builder gaps and are not reported.",
     "- D1 is empirical: \"compatible\" means the builder found a witness, and \"unsupported\" is not a proof of conflict.", "",
     "## Pairwise results", "",
     "| status | pairs |", "|---|---|"]
for k, v in S["counts"].items():
    L.append(f"| {k.replace('_', ' ')} | {v} |")
cs = S["compatible_share"]
L += ["", f"Proven conflicts by basis: {S['proven_by_basis'].get('official', 0)} need only the official verifiers; "
      f"{S['proven_by_basis'].get('plain', 0)} need a frozen plain-meaning check (a loophole response could pass the "
      "official verifiers alone).", "",
      f"Compatible pairs: median success share {cs['median']}, {cs['all_versions']} pairs with every version passing, {cs['below_0.5']} below "
      f"0.5, {cs['below_0.1']} below 0.1 (lowest {cs['min']}).", "",
      f"`ratio:overlap`: {S['overlap_tasks']['tasks_with_any_witness']} of {S['overlap_tasks']['tasks_tried']} "
      f"provisional tasks got at least one witness; the draw-level success share is "
      f"{S['overlap_tasks']['draw_success_share']}.", "",
      f"Builder time summed over all versions: {round(S['final_run_seconds'] / 3600, 1)} h of CPU (4 workers).", "",
      "### Proven conflicts", "", "| pair | basis | argument |", "|---|---|---|"]
for p, (basis, arg) in sorted(P.proven().items()):
    L.append(f"| {c(p)} | {basis} | {arg.replace('|', '/')} |")
L += ["", "### Unsupported by the builder", "", "| pair | why | main builder failure |", "|---|---|---|"]
for u in sorted(S["unsupported_by_builder"], key=lambda u: (u["why"], u["pair"])):
    note = P.loophole_only().get(tuple(u["pair"]), "") or u.get("note", "")
    why = WHY[u["why"]] + (f": {note}" if note else "")
    L.append(f"| {c(u['pair'])} | {why} | {u['top_reasons'][0][0] if u['top_reasons'] else ''} |")
L += ["", "### Compatible but rare (success share below 0.1)", "", "| pair | witnesses / versions |", "|---|---|"]
for p, n, v in S["low_share_pairs"]:
    L.append(f"| {c(p)} | {n} / {v} |")
L += ["", "### Per type", "", "| type | compatible partners (of 41) | proven | unsupported | mean share |", "|---|---|---|---|---|"]
for t, v in sorted(S["per_type"].items(), key=lambda x: x[1]["compatible"]):
    L.append(f"| `{t}` | {v['compatible']} | {v['proven']} | {v['unsupported']} | {v['mean_share']} |")

pl = S.get("six_rule_pilot")
if pl:
    L += ["", "## Six-rule feasibility pilot (estimate)", "",
          f"{pl['pools']} random pools of six distinct types, sampled by sequential uniform proposals that skip every "
          "blocked pair (proven or unsupported), with fresh default parameters. One joint witness with up to 24 attempts "
          "per pool. This estimates how often stage 5 will have to redraw a pool; it is not exhaustive.", "",
          f"**Accepted: {pl['accepted']} of {pl['pools']} pools ({pl['acceptance']:.0%}).** Builder time per pool: "
          f"median {pl['seconds']['median']} s, max {pl['seconds']['max']} s. Witness length: median "
          f"{pl['witness_words']['median']} words, max {pl['witness_words']['max']}.", "",
          "| type | pools | accepted | acceptance |", "|---|---|---|---|"]
    for t, v in sorted(pl["per_type"].items(), key=lambda x: x[1]["acceptance"]):
        L.append(f"| `{t}` | {v['pools']} | {v['accepted']} | {v['acceptance']:.0%} |")
    if pl["types_never_sampled"]:
        L += ["", "Never sampled: " + ", ".join(f"`{t}`" for t in pl["types_never_sampled"])]
    L += ["", "Most common failure reasons in rejected pools:", ""]
    for k, v in pl["top_failure_reasons"]:
        L.append(f"- {k} ({v} attempts)")

L += ["", "## Hand witnesses", "",
      "Each passes both official verifiers and both plain checks (`tests/test_stage3_proofs.py`).", ""]
for p, (rules, text) in sorted(P.hand_witnesses().items()):
    L += [f"- {c(p)}" + (f" (sep `{rules['format:list']['sep']}`)" if "format:list" in rules else ""), "",
          "  ```", *("  " + ln for ln in text.split("\n")), "  ```", ""]

(IFB / "docs" / "stage3_report.md").write_text("\n".join(L) + "\n")
print("wrote docs/stage3_report.md", len(L), "lines")
