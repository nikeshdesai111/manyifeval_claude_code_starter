"""Stage-2 report: witness-builder capability on single types and hand-picked pairs.

Single types: 50 default parameter draws each (24 attempts per draw).
Pairs: hand-picked, 20 draws each (24 attempts per draw). This is NOT the stage-3 audit.
Writes freeze/stage2_builder.json and docs/stage2_report.md.
Usage: python scripts/stage2_report.py
"""
import collections
import json
import sys
import time
from pathlib import Path

IFB = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(IFB / "src"))
from mife_ifb import inventory, source, witness  # noqa: E402

TASK = ("Write a short story about a lighthouse keeper who finds a message in a bottle on the beach "
        "and decides to answer it.")
SEED = 20261123

LIKELY_COMPATIBLE = [
    ("words:alphabet", "format:title_case"), ("words:alphabet", "count:person_names"),
    ("words:prime_lengths", "format:newline"), ("ratio:sentence_type", "count:punctuation"),
    ("ratio:sentence_balance", "count:punctuation"), ("sentence:increment", "count:word_count_range"),
    ("words:last_first", "sentence:increment"), ("format:list", "format:line_indent"),
    ("format:sub-bullets", "format:line_indent"), ("format:output_template", "format:title_case"),
    ("format:thesis", "words:paragraph_last_first"), ("format:quotes", "format:quote_unquote"),
    ("format:parentheses", "format:emoji"), ("words:vowel", "count:conjunctions"),
    ("words:consonants", "words:no_consecutive"), ("words:odd_even_syllables", "words:no_consecutive"),
    ("ratio:stop_words", "count:pronouns"), ("count:unique_word_count", "words:repeats"),
    ("words:words_position", "words:start_verb"), ("sentence:keyword", "words:keywords_specific_position"),
    ("ratio:overlap", "format:list"), ("ratio:sentence_words", "format:emoji"),
    ("format:no_whitespace", "count:numbers"), ("words:palindrome", "words:repeats"),
    ("count:word_count_range", "count:unique_word_count"), ("words:alphabet", "words:consonants"),
]
EXPECTED_CONFLICT = [
    ("format:list", "format:sub-bullets"), ("ratio:sentence_type", "ratio:sentence_balance"),
    ("words:alphabet", "words:last_first"), ("words:no_consecutive", "sentence:alliteration_increment"),
    ("words:alphabet", "count:numbers"), ("format:newline", "words:vowel"),
    ("format:no_whitespace", "count:unique_word_count"), ("format:output_template", "words:prime_lengths"),
    ("count:keywords_multiple", "words:repeats"),
]


def run(types, draws, idx):
    ok, t0, reasons, example = 0, time.time(), collections.Counter(), None
    for d in range(draws):
        rules = {t: source.sample_default_kwargs(t, rng_seed=SEED + idx * 1000 + d * 10 + k) for k, t in enumerate(types)}
        r = witness.build_witness(rules, task_text=TASK, seed=d)
        ok += r.ok
        reasons.update(r.reasons)
        if r.ok and example is None:
            example = {"rules": {t: {k: v for k, v in kw.items() if k != "reference_text"} for t, kw in rules.items()},
                       "text": r.text}
    return {"types": list(types), "draws": draws, "success": ok, "seconds": round(time.time() - t0, 1),
            "top_failure_reasons": reasons.most_common(3), "example": example}


def main():
    singles = [run([t], 50, i) for i, t in enumerate(inventory.candidates())]
    pairs = [dict(run(p, 20, 500 + i), group="likely compatible") for i, p in enumerate(LIKELY_COMPATIBLE)]
    pairs += [dict(run(p, 20, 800 + i), group="expected conflict") for i, p in enumerate(EXPECTED_CONFLICT)]
    (IFB / "freeze" / "stage2_builder.json").write_text(json.dumps({"singles": singles, "pairs": pairs}, indent=2,
                                                                   ensure_ascii=False) + "\n")
    L = ["# Stage 2 report: witness builder", "",
         "Generated by `scripts/stage2_report.py`. Each draw takes fresh parameters from the released default "
         "generators and gives the builder up to 24 seeded attempts. Every success passed the official verifier "
         "and the frozen plain-meaning check for each rule. This is a capability check, not the stage-3 audit: "
         "a failure here is not a verdict.", "",
         f"Reference text for `ratio:overlap`: \"{TASK}\" (a stand-in until stage 4 produces the cleaned tasks).", "",
         "## Single types (50 draws each)", "", "| type | success | seconds | main failure reason |", "|---|---|---|---|"]
    for r in singles:
        why = r["top_failure_reasons"][0][0] if r["success"] < r["draws"] else ""
        L.append(f"| `{r['types'][0]}` | {r['success']}/{r['draws']} | {r['seconds']} | {why} |")
    n_full = sum(r["success"] == r["draws"] for r in singles)
    L += ["", f"{n_full} of {len(singles)} types succeed on every draw.", "",
          "## Hand-picked pairs (20 draws each)", "", "| pair | group | success | main failure reason |", "|---|---|---|---|"]
    for r in pairs:
        why = r["top_failure_reasons"][0][0][:120] if r["success"] < r["draws"] else ""
        L.append(f"| `{r['types'][0]}` + `{r['types'][1]}` | {r['group']} | {r['success']}/{r['draws']} | {why} |")
    L += ["", "## Example witnesses", ""]
    for r in pairs[:6]:
        if r["example"]:
            L += [f"**{' + '.join(r['types'])}**", "", "```", r["example"]["text"][:600], "```", ""]
    (IFB / "docs" / "stage2_report.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L[:200]))


if __name__ == "__main__":
    main()
