"""Stage-1 report: pinning, environment, 43-type inventory, default-generator smoke test, drift audit.

Writes freeze/inventory.json, freeze/stage1_audit.json and docs/stage1_report.md.
Usage: python scripts/stage1_report.py
"""
import collections
import json
import sys
from pathlib import Path

IFB = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(IFB / "src"))
from mife_ifb import inventory, plain_meaning as pm, source  # noqa: E402
from mife_ifb.config import load_config  # noqa: E402

DRAWS = 200


def default_smoke() -> dict:
    """Draw each candidate's released default generator DRAWS times; record parameter ranges and wording."""
    seed0 = load_config()["seeds"]["plain_meaning_examples"]
    out = {}
    for i, t in enumerate(inventory.candidates()):
        vals = collections.defaultdict(list)
        texts = set()
        for j in range(DRAWS):
            kw = source.sample_default_kwargs(t, rng_seed=seed0 * 1000 + i * DRAWS + j)
            if t in source.types_reading_task_text():
                kw.pop("reference_text", None)
            for k, v in kw.items():
                vals[k].append(v)
            texts.add(source.render_rule_text(t, kw))
        summ = {}
        for k, v in vals.items():
            if all(isinstance(x, int) for x in v):
                summ[k] = {"min": min(v), "max": max(v), "distinct": len(set(v))}
            else:
                summ[k] = {"distinct": len(set(map(str, v))), "examples": sorted(set(map(str, v)))[:5]}
        out[t] = {"parameters": summ, "distinct_wordings": len(texts), "example_wording": sorted(texts)[0],
                  "shim": t in source.DEFAULT_SHIMS}
    return out


def md_table(rows, cols):
    o = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    o += ["| " + " | ".join(str(r[c]).replace("|", "\\|") for c in cols) + " |" for r in rows]
    return "\n".join(o)


def main():
    pins = source.verify_pinned()
    pkgs = source.check_package_pins()
    env = source.environment_fingerprint()
    inv = inventory.table()
    cands, par, fix = inventory.candidates(), inventory.parameterized(), inventory.fixed()
    smoke = default_smoke()
    drift = source.released_prompt_drift()
    (IFB / "freeze" / "inventory.json").write_text(json.dumps(
        {"ood_types": len(inv), "excluded": inventory.EXCLUDED, "candidates": cands,
         "parameterized": par, "fixed": fix, "reads_task_text": source.types_reading_task_text(),
         "table": inv}, indent=2, ensure_ascii=False) + "\n")
    audit = {"pins": pins, "packages": pkgs, "environment": env, "default_smoke": smoke, "drift": drift}
    (IFB / "freeze" / "stage1_audit.json").write_text(json.dumps(audit, indent=2, ensure_ascii=False) + "\n")

    cat = collections.Counter(source.category_of(t) for t in cands)
    rows = []
    for t in cands:
        s = smoke[t]
        ps = "; ".join(f"{k}: {v['min']}–{v['max']}" if "min" in v else f"{k}: {v['distinct']} values"
                       for k, v in s["parameters"].items()) or "fixed"
        rows.append({"type": f"`{t}`", "parameters (200 default draws)": ps,
                     "example wording": s["example_wording"][:110] + ("…" if len(s["example_wording"]) > 110 else ""),
                     "plain-meaning check adds": "yes" if pm.CHECKS[t].loophole else "G1 only"})
    exc = [{"type": f"`{t}`", "reason": r} for t, r in inventory.EXCLUDED.items()]
    L = ["# Stage 1 report: IFBench loaded, plain-meaning checks frozen", "",
         "Generated by `scripts/stage1_report.py`. Nothing here generates responses, samples pools or reads tasks for grouping.", "",
         "## Pinning", "",
         f"- IFBench commit `{pins['commit']}` (package {load_config()['source']['package_version']}), clean checkout.",
         f"- Test file sha256 `{pins['test_file_sha256']}`.",
         "- NLTK data vendored (the only search path, downloads disabled): "
         + ", ".join(f"`{k}`" for k in pins["nltk"]) + "; each zip matches NLTK's published checksum.",
         "- Verifier dependencies: " + ", ".join(f"{k} {v}" for k, v in pkgs.items()) + f"; Python {env['python']}.", "",
         "## Inventory", "",
         f"IFBench has {len(inv)} out-of-distribution types; {len(inventory.EXCLUDED)} are excluded, leaving "
         f"**{len(cands)} candidates: {len(par)} parameterized and {len(fix)} fixed**. By category: "
         + ", ".join(f"{k} {v}" for k, v in sorted(cat.items())) + ". "
         f"Only {', '.join('`'+t+'`' for t in source.types_reading_task_text())} reads the task text.", "",
         md_table(exc, ["type", "reason"]), "",
         "### Candidates and their released default generators", "",
         md_table(rows, ["type", "parameters (200 default draws)", "example wording", "plain-meaning check adds"]), "",
         "## Findings in the released code", "",
         "1. **`count:words_japanese` default generator crashes.** `build_description()` with no arguments raises "
         "`TypeError` (it tests `N % 10` on the argument, not the drawn value). The adapter draws N exactly as the "
         "released default would (`random.randint(1, 30)`, one call on the same RNG) and passes it in. Wording is unchanged.",
         "2. **`count:words_japanese` wording drops the word \"word\" for some N.** For every N ending in 1, 2 or 3 the "
         "text reads e.g. \"Every 21st of your response must be in Japanese.\" (and \"11st\", \"12nd\", \"13rd\"); about "
         "30% of draws. Kept exactly, per the decision to preserve official wording. N = 1 asks for every word to be Japanese.",
         "3. **NLTK 3.10.4 refuses data directories that are group-writable.** `fetch_source.sh` now runs `chmod -R go-w` on the vendored data.",
         "4. No candidate renders a multi-line instruction, so the ManyIFEval one-rule-per-line layout works unchanged.", "",
         "## Released-prompt drift audit", "",
         f"{drift['rows_verbatim']} of {drift['rows']} released prompts contain every instruction text exactly as the pinned "
         f"code renders it (rows by constraint count: {drift['constraints_per_row']}). The rest come from older template "
         "wordings; this affects only how stage 4 strips the constraint text to get base tasks, not our rule wording.", "",
         md_table([{"type": f"`{k}`", "rows with drift": v} for k, v in list(drift["drift_by_type"].items())[:15]],
                  ["type", "rows with drift"]), "",
         "## Plain-meaning checks", "",
         f"One check per candidate type, frozen in `freeze/plain_meaning_frozen.json`; the full table is "
         f"`docs/plain_meaning_checks.md`. {sum(c.loophole is not None for c in pm.CHECKS.values())} types add a "
         "condition with a tested loophole example; the rest rely on G1 plus the official verifier.", ""]
    (IFB / "docs" / "stage1_report.md").write_text("\n".join(L), encoding="utf-8")
    print(json.dumps({"candidates": len(cands), "parameterized": len(par), "fixed": len(fix),
                      "drift_verbatim": drift["rows_verbatim"]}, indent=2))


if __name__ == "__main__":
    main()
